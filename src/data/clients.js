// Summary only — no personal data sent to AI
export function getAISafeSummary(clients) {
  const normalizedClients = clients.map(normalizeClient);
  const activeGod = normalizedClients.filter((c) => c.tier === "GOD");
  const owedQueue = normalizedClients.filter(
    (c) => c.giftStillOwed && !c.giftDone,
  );
  const formerGodOwed = normalizedClients.filter(
    (c) => c.previousTier === "GOD" && c.tier !== "GOD" && c.giftStillOwed,
  );
  const waitlistGod = normalizedClients.filter(
    (c) => c.isWaitlist && c.tier === "GOD" && !c.giftDone,
  );
  const overdueFiveDays = normalizedClients.filter(
    (c) => (c.loanOverdueDays || 0) >= 5,
  );
  const byTier = {};

  TIERS.forEach((tier) => {
    const group = normalizedClients.filter((client) => client.tier === tier);
    byTier[tier] = {
      total: group.length,
      done: group.filter((client) => client.giftDone).length,
      pending: group.filter((client) => client.giftStillOwed && !client.giftDone)
        .length,
      withLoan: group.filter((client) => client.loan).length,
    };
  });

  const total = normalizedClients.length;
  const done = normalizedClients.filter((client) => client.giftDone).length;

  return `
Gift tracking summary (aggregated, no personal data):
- Total tracked clients: ${total}
- Current GOD clients: ${activeGod.length}
- Gifts delivered: ${done}
- Gift obligation queue still open: ${owedQueue.length}
- Former GOD clients still owed a gift: ${formerGodOwed.length}
- New GOD clients from waitlist: ${waitlistGod.length}
- Loan overdue 5+ days: ${overdueFiveDays.length}
- By tier: ${TIERS.map((tier) => `${tier}: ${byTier[tier].total} total, ${byTier[tier].done} delivered, ${byTier[tier].pending} still owed, ${byTier[tier].withLoan} with loan`).join(" | ")}
- Report date: ${new Date().toISOString().split("T")[0]}
  `.trim();
}
