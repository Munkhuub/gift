export function normalizeClient(client) {
  return {
    id: Number(client.id),
    last: client.last || "",
    first: client.first || "",
    phone: client.phone || "",
    tier: client.tier || "FAN",
    giftDone: Boolean(client.giftDone),
    giftDate: client.giftDate || "",
    loan: Boolean(client.loan),
    note: client.note || "",
    giftType: client.giftType || "",
    deliveredBy: client.deliveredBy || "",
  };
}

