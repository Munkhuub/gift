export const TIERS = ["GOD", "KING", "BOSS", "STAR", "FAN"];

export function normalizeClient(client) {
  return {
    id: Number(client.id),
    last: client.last || "",
    first: client.first || "",
    phone: client.phone || "",
    tier: client.tier || "GOD",
    previousTier: client.previousTier || "",
    giftDone: Boolean(client.giftDone),
    giftStillOwed:
      client.giftStillOwed === undefined
        ? !Boolean(client.giftDone)
        : Boolean(client.giftStillOwed),
    giftEligibilityStatus:
      client.giftEligibilityStatus ||
      (client.giftDone ? "DELIVERED" : "PENDING"),
    giftDate: client.giftDate || "",
    loan: Boolean(client.loan),
    loanOverdueDays: Number(client.loanOverdueDays || 0),
    isWaitlist: Boolean(client.isWaitlist),
    tierChangedAt: client.tierChangedAt || "",
    statusReason: client.statusReason || "",
    note: client.note || "",
    giftType: client.giftType || "",
    deliveredBy: client.deliveredBy || "",
  };
}

