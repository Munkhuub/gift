// Summary only — no personal data sent to AI
export function getAISafeSummary(clients) {
  const normalizedClients = clients.map(normalizeClient);
  const byTier = {};
  TIERS.forEach((t) => {
    const group = normalizedClients.filter((c) => c.tier === t);
    byTier[t] = {
      total: group.length,
      done: group.filter((c) => c.giftDone).length,
      pending: group.filter((c) => !c.giftDone).length,
      withLoan: group.filter((c) => c.loan).length,
    };
  });
  const total = normalizedClients.length;
  const done = normalizedClients.filter((c) => c.giftDone).length;
  return `
Gift tracking summary (aggregated, no personal data):
- Total tracked clients: ${total}
- Gifts delivered: ${done}
- Gifts pending: ${total - done}
- By tier: ${TIERS.map((t) => `${t}: ${byTier[t].total} total, ${byTier[t].done} delivered, ${byTier[t].pending} pending, ${byTier[t].withLoan} with loan`).join(" | ")}
- Report date: ${new Date().toISOString().split("T")[0]}
  `.trim();
}
